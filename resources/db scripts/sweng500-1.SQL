CREATE TABLE ORGANIZATIONS_ADDRESSES
(
	ORGANIZATION_ID NVARCHAR(40) NOT NULL,
	ADDRESS_ID NVARCHAR(40) NOT NULL,
	PRIMARY KEY (ORGANIZATION_ID, ADDRESS_ID),
	KEY (ADDRESS_ID),
	KEY (ORGANIZATION_ID)
) 
;


CREATE TABLE ORGANIZATIONS
(
	ID NVARCHAR(40) NOT NULL,
	NAME NVARCHAR(75),
	PRIMARY KEY (ID),
	UNIQUE (NAME)
) 
;


CREATE TABLE USERS_ADDRESSES
(
	USER_ID NVARCHAR(40) NOT NULL,
	ADDRESS_ID NVARCHAR(40) NOT NULL,
	TYPE NVARCHAR(50),
	PRIMARY KEY (USER_ID, ADDRESS_ID),
	KEY (ADDRESS_ID),
	KEY (USER_ID)
) 
;


CREATE TABLE ADDRESSES
(
	ID NVARCHAR(40) NOT NULL,
	NAME NVARCHAR(75) NOT NULL,
	ADDRESS_LINE_1 NVARCHAR(100),
	ADDRESS_LINE_2 NVARCHAR(100),
	CITY NVARCHAR(50),
	STATE_OR_PROVINCE NVARCHAR(25),
	POSTAL_CODE NVARCHAR(15),
	LATITUDE FLOAT(15),
	LONGITUDE FLOAT(15),
	PRIMARY KEY (ID)
) 
;


CREATE TABLE USERS
(
	ID NVARCHAR(40) NOT NULL,
	USER_NAME NVARCHAR(50),
	PASSWORD NVARCHAR(50),
	GIVEN_NAME NVARCHAR(150),
	SURNAME NVARCHAR(150),
	ORGANIZATION_ID NVARCHAR(40),
	PRIMARY KEY (ID),
	UNIQUE (USER_NAME),
	KEY (ORGANIZATION_ID)
) 
;





ALTER TABLE ORGANIZATIONS_ADDRESSES ADD CONSTRAINT FK_ORGANIZATIONS_ADDRESSES_ADDRESSES 
	FOREIGN KEY (ADDRESS_ID) REFERENCES ADDRESSES (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE ORGANIZATIONS_ADDRESSES ADD CONSTRAINT FK_ORGANIZATIONS_ADDRESSES_ORGANIZATIONS 
	FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE USERS_ADDRESSES ADD CONSTRAINT FK_USERS_ADDRESSES_ADDRESSES 
	FOREIGN KEY (ADDRESS_ID) REFERENCES ADDRESSES (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE USERS_ADDRESSES ADD CONSTRAINT FK_USERS_ADDRESSES_USERS 
	FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE USERS ADD CONSTRAINT FK_USERS_ORGANIZATIONS 
	FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS (ID)
;
