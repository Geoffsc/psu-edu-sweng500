CREATE TABLE ORGANIZATIONS
(
	ID NVARCHAR(40) NOT NULL,
	NAME NVARCHAR(75),
	PRIMARY KEY (ID),
	UNIQUE (NAME)
) 
;


CREATE TABLE ADDRESSES
(
	ID NVARCHAR(40) NOT NULL,
	NAME NVARCHAR(75) NOT NULL,
	ADDRESS_LINE_1 NVARCHAR(100),
	ADDRESS_LINE_2 NVARCHAR(100),
	CITY NVARCHAR(50),
	STATE_OR_PROVINCE NVARCHAR(25),
	POSTAL_CODE NVARCHAR(15),
	LATITUDE FLOAT(15),
	LONGITUDE FLOAT(15),
	PRIMARY KEY (ID)
) 
;


CREATE TABLE TRIPS_MEMBERS
(
	TRIP_ID NVARCHAR(40) NOT NULL,
	MEMBER_ID NVARCHAR(40) NOT NULL,
	TYPE NVARCHAR(50),
	PRIMARY KEY (TRIP_ID, MEMBER_ID),
	KEY (TRIP_ID),
	KEY (MEMBER_ID)
) 
;


CREATE TABLE TRIPS
(
	ID NVARCHAR(40) NOT NULL,
	TITLE NVARCHAR(75),
	START_ADDRESS NVARCHAR(40) NOT NULL,
	END_ADDRESS NVARCHAR(40),
	START_DATE_TIME DATETIME,
	END_DATE_TIME DATETIME,
	ORGANIZATION_ID NVARCHAR(40),
	PRIMARY KEY (ID),
	UNIQUE (TITLE),
	KEY (END_ADDRESS),
	KEY (ORGANIZATION_ID),
	KEY (START_ADDRESS)
) 
;


CREATE TABLE USERS
(
	ID NVARCHAR(40) NOT NULL,
	USER_NAME NVARCHAR(50),
	PASSWORD NVARCHAR(50),
	GIVEN_NAME NVARCHAR(150),
	SURNAME NVARCHAR(150),
	ORGANIZATION_ID NVARCHAR(40),
	PRIMARY KEY (ID),
	UNIQUE (USER_NAME),
	KEY (ORGANIZATION_ID)
) 
;





ALTER TABLE TRIPS_MEMBERS ADD CONSTRAINT FK_TRIPS_MEMBERS_TRIPS 
	FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE TRIPS_MEMBERS ADD CONSTRAINT FK_TRIPS_MEMBERS_USERS 
	FOREIGN KEY (MEMBER_ID) REFERENCES USERS (ID)
	ON DELETE CASCADE ON UPDATE CASCADE
;

ALTER TABLE TRIPS ADD CONSTRAINT FK_TRIPS_ADDRESSES_END_ADDRESS 
	FOREIGN KEY (END_ADDRESS) REFERENCES ADDRESSES (ID)
;

ALTER TABLE TRIPS ADD CONSTRAINT FK_TRIPS_ORGANIZATIONS 
	FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS (ID)
;

ALTER TABLE TRIPS ADD CONSTRAINT FK_TRIPS_ADDRESSES_START_ADDRESS 
	FOREIGN KEY (START_ADDRESS) REFERENCES ADDRESSES (ID)
;

ALTER TABLE USERS ADD CONSTRAINT FK_USERS_ORGANIZATIONS 
	FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS (ID)
;
